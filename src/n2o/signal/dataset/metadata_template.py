from __future__ import annotations

import importlib.util
from pathlib import Path

from .library import DatasetInfo

METADATA_FILENAME = "dataset_info.py"
"""Name `DatasetLoader(path=...)` looks for inside `path` for a local recording's
metadata -- a sibling to the recording files themselves, so the metadata travels with the
folder rather than living in a separate registry only this codebase knows about."""

_TEMPLATE = '''"""Metadata for this dataset folder -- generated by
`n2o.signal.dataset.write_metadata_template()`.

Fill in the fields below (delete the TODO comments as you go), place this file inside
the recording folder itself (next to the recording's own files) if it isn't already,
then load it with `DatasetLoader(path=...).info()`. See `n2o.signal.dataset.DatasetInfo`
for what each field means.
"""

from n2o.signal.dataset import DatasetInfo

DATASET_INFO = DatasetInfo(
    source=None,  # TODO: paper/dataset this recording came from (authors, year, DOI)
    cue_onset_sec=None,  # TODO: seconds into a trial where the cue/event appears, if any
    data_range_sec=None,  # TODO: (start, end) seconds relative to the cue this covers
    num_channels=None,  # TODO: number of signal channels
    metadata={
        # TODO: anything else worth recording, e.g. "sampling_rate_hz": ..., "montage": ...
    },
)
'''


def metadata_path(folder: Path) -> Path:
    return folder / METADATA_FILENAME


def write_template(folder: Path) -> Path:
    """Write a blank `DatasetInfo` template into `folder`. Refuses to overwrite."""
    target = metadata_path(folder)
    if target.exists():
        raise FileExistsError(
            f"metadata file already exists at {target}; delete it first, or construct "
            "DatasetLoader(path=...) to load it as-is"
        )
    folder.mkdir(parents=True, exist_ok=True)
    target.write_text(_TEMPLATE)
    return target


def load(folder: Path) -> DatasetInfo:
    """Load the `DatasetInfo` a prior `write_template()` call produced (and the user filled in)."""
    target = metadata_path(folder)
    if not target.exists():
        raise FileNotFoundError(
            f"no metadata file at {target}; call write_template()/write_metadata_template() "
            "to create one, fill it in, then call info() again"
        )
    spec = importlib.util.spec_from_file_location("_n2o_dataset_metadata", target)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    info = getattr(module, "DATASET_INFO", None)
    if not isinstance(info, DatasetInfo):
        raise TypeError(f"{target} must define DATASET_INFO = DatasetInfo(...)")
    return info
